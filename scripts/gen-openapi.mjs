// Generates OPENAPI.yaml (route inventory) from the App Router API folder. Request/response schemas live in
// each route's Zod validators and are not duplicated here; permissions are read from the route source.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve('src/app/api/v1');
const out = [];
function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name === 'route.ts') out.push(p);
  }
}
walk(ROOT);
const paths = {};
for (const file of out.sort()) {
  const rel = path.relative(ROOT, path.dirname(file)).split(path.sep).join('/');
  const urlPath = '/api/v1/' + rel.replace(/\[(\w+)\]/g, '{$1}');
  const src = fs.readFileSync(file, 'utf8');
  const perms = [...new Set([...src.matchAll(/PERMISSIONS\.(\w+)/g)].map((m) => m[1]))];
  const methods = [...src.matchAll(/export const (GET|POST|PUT|PATCH|DELETE) =/g)].map((m) => m[1]);
  const usesIdem = /idempotencyKeyOf/.test(src);
  const multipart = /formData\(\)/.test(src);
  paths[urlPath] ??= {};
  for (const m of methods) {
    const op = {
      summary: `${m} ${urlPath}`,
      'x-source': path.relative('.', file).split(path.sep).join('/'),
      'x-permissions': perms.length ? perms : ['authenticated'],
      responses: {
        200: { description: 'Success envelope { data, meta?, requestId }' },
        400: { description: 'VALIDATION_ERROR' },
        401: { description: 'UNAUTHORIZED' },
        403: { description: 'FORBIDDEN' },
        404: { description: 'NOT_FOUND' },
        409: { description: 'CONFLICT / STOCK_CHANGED / PRICE_CHANGED / IMPORT_STALE_APPROVAL_REQUIRED' },
        422: { description: 'SHIPPING_RULE_MISSING' },
        429: { description: 'RATE_LIMITED' },
      },
    };
    if (usesIdem) op.parameters = [{ name: 'Idempotency-Key', in: 'header', required: true, schema: { type: 'string', minLength: 8, maxLength: 128 } }];
    if (multipart) op.requestBody = { content: { 'multipart/form-data': { schema: { type: 'object', properties: { file: { type: 'string', format: 'binary' } } } } } };
    else if (['POST', 'PUT', 'PATCH'].includes(m)) op.requestBody = { content: { 'application/json': { schema: { type: 'object', description: 'See Zod schema in x-source' } } } };
    paths[urlPath][m.toLowerCase()] = op;
  }
}
const doc = [
  "openapi: 3.0.3",
  "info:",
  "  title: B2B-STORE API v1 (route inventory)",
  "  version: 1.0.0",
  "  description: >-",
  "    Generated by scripts/gen-openapi.mjs from src/app/api/v1. Lists every route, method, permission and",
  "    idempotency requirement. Field-level schemas are the Zod validators in each route (x-source). Local use only.",
  "servers:",
  "  - url: http://127.0.0.1:3200",
  "components:",
  "  securitySchemes:",
  "    sessionCookie: { type: apiKey, in: cookie, name: b2b_session }",
  "security:",
  "  - sessionCookie: []",
  "paths:",
].concat([]);
const yamlLines = [...doc];
function y(obj, indent) {
  for (const [k, v] of Object.entries(obj)) {
    const pad = '  '.repeat(indent);
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      yamlLines.push(`${pad}${JSON.stringify(k)}:`);
      y(v, indent + 1);
    } else if (Array.isArray(v)) {
      yamlLines.push(`${pad}${JSON.stringify(k)}: ${JSON.stringify(v)}`);
    } else {
      yamlLines.push(`${pad}${JSON.stringify(k)}: ${JSON.stringify(v)}`);
    }
  }
}
y(paths, 1);
fs.writeFileSync('OPENAPI.yaml', yamlLines.join('\n') + '\n');
console.log(`routes: ${out.length}, paths: ${Object.keys(paths).length}`);
